import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
import { chromium } from 'playwright'
import AxeBuilder from '@axe-core/playwright'

const browser = await chromium.launch({ channel: process.env.BROWSER_CHANNEL || 'msedge', headless: true })
const context = await browser.newContext({ permissions: ['clipboard-read', 'clipboard-write'] })
const page = await context.newPage()
const base = process.env.TEST_URL || 'http://127.0.0.1:4173'
const errors = []
page.on('pageerror', error => errors.push(error.message))
page.on('console', message => {
  if (message.type() === 'error' && message.text().includes('Encountered two children with the same key')) errors.push(message.text())
})
const assertCaseStudy = async title => {
  await page.getByRole('region', { name: title, exact: true }).waitFor()
  assert.equal(await page.locator('#case-study > .project-image').count(), 1, `${title} must show exactly one artwork panel`)
  assert.equal(await page.locator('#case-study > .case-content').count(), 1, `${title} must show exactly one details panel`)
  assert.equal(await page.locator('#case-title').textContent(), title)
  assert.equal(await page.locator('.project-card.is-selected h3').textContent(), title)
  assert.equal(await page.locator('.project-view[aria-expanded="true"]').count(), 1)
}
await mkdir('.artifacts', { recursive: true })
try {
  for (const width of [360, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 1000 })
    await page.goto(base)
    await page.evaluate(() => document.fonts.ready)
    assert.equal(await page.getByRole('heading', { level: 1 }).count(), 1)
    assert.equal(await page.locator('.project-card').count(), 10)
    assert.equal(await page.getByText('Open for freelance', { exact: true }).count(), 0)
    const sizes = await page.evaluate(() => ({ viewport: innerWidth, content: document.documentElement.scrollWidth }))
    assert(sizes.content <= sizes.viewport, `Page overflows at ${width}px: ${sizes.content}px`)
    const accessibility = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
    assert.deepEqual(accessibility.violations.map(item => ({ id: item.id, targets: item.nodes.map(node => node.target) })), [], `Accessibility violations at ${width}px`)
    await page.locator('img').evaluateAll(images => Promise.all(images.map(image => { image.loading = 'eager'; return image.decode().catch(() => {}) })))
    await page.screenshot({ path: `.artifacts/portfolio-${width}.png`, fullPage: true })
    await page.screenshot({ path: `.artifacts/hero-${width}.png` })
  }
  console.log('Responsive layouts and accessibility checks passed.')
  await page.locator('nav a[href="#work"]').click()
  await page.waitForFunction(() => Math.abs(document.querySelector('#work').getBoundingClientRect().top - parseFloat(getComputedStyle(document.documentElement).scrollPaddingTop)) < 2)
  assert.equal(await page.evaluate(() => location.hash), '#work', 'Section navigation must preserve shareable anchors')
  assert.equal(await page.evaluate(() => getComputedStyle(document.documentElement).scrollBehavior), 'smooth')
  await page.getByRole('button', { name: 'Unity, 5 projects', exact: true }).click()
  assert.equal(await page.locator('.project-card').count(), 5)
  await page.getByRole('button', { name: 'View Viewfinder case study', exact: true }).click()
  await page.getByRole('region', { name: 'Viewfinder', exact: true }).waitFor()
  assert.equal(await page.locator('.project-card.is-selected').count(), 1)
  await page.waitForFunction(() => {
    const panel = document.querySelector('#case-study')
    const header = document.querySelector('header')
    return Math.abs(panel.getBoundingClientRect().top - header.getBoundingClientRect().height - 20) < 2
  })
  const panelPosition = await page.locator('#case-study').boundingBox()
  const headerPosition = await page.locator('header').boundingBox()
  assert(panelPosition.y >= headerPosition.height, 'Sticky header obscures the case study')
  await page.getByRole('button', { name: 'Previous project', exact: true }).click()
  await assertCaseStudy('KiX Dream Soccer')
  assert.equal(await page.locator('#case-study .is-placeholder').count(), 1, 'Projects without artwork must show their placeholder')
  await page.getByRole('button', { name: 'Next project', exact: true }).click()
  await assertCaseStudy('Viewfinder')
  assert.equal(await page.locator('#case-study .is-placeholder').count(), 0, 'Switching back must restore the project artwork')
  await page.keyboard.press('Escape')
  assert.equal(await page.locator('#case-study').count(), 0)
  assert.equal(await page.locator('.project-card button:focus').count(), 1, 'Closing should restore card focus')
  await page.keyboard.press('Enter')
  await page.getByRole('region', { name: 'Viewfinder', exact: true }).waitFor()
  await page.getByRole('button', { name: 'Close, — OPEN Viewfinder case study', exact: true }).click()
  assert.equal(await page.locator('#case-study').count(), 0)
  await page.getByRole('button', { name: 'HTML5 / Pixi, 1 projects', exact: true }).click()
  await page.getByRole('button', { name: 'View Video Slot Portfolio case study', exact: true }).click()
  await page.getByRole('button', { name: 'Next project', exact: true }).click()
  assert.equal(await page.locator('#case-title').textContent(), 'Video Slot Portfolio', 'One-project filter must cycle safely')
  await assertCaseStudy('Video Slot Portfolio')
  await page.getByRole('button', { name: 'All, 10 projects', exact: true }).click()
  assert.equal(await page.locator('#case-study').count(), 0)

  console.log('Project filters, case navigation, keyboard controls, and focus restoration passed.')
  for (const { width, reducedMotion } of [{ width: 360, reducedMotion: 'no-preference' }, { width: 1440, reducedMotion: 'reduce' }]) {
    await page.setViewportSize({ width, height: 1000 })
    await page.emulateMedia({ reducedMotion })
    const titles = await page.locator('.project-card h3').allTextContents()
    await page.getByRole('button', { name: `View ${titles[0]} case study`, exact: true }).click()
    await assertCaseStudy(titles[0])
    for (const direction of [1, -1]) {
      for (let step = 1; step <= titles.length * 2; step++) {
        await page.getByRole('button', { name: direction === 1 ? 'Next project' : 'Previous project', exact: true }).click()
        await assertCaseStudy(titles[(direction * step % titles.length + titles.length) % titles.length])
      }
    }
    for (let attempt = 0; attempt < 3; attempt++) {
      await page.getByRole('button', { name: 'Close case study', exact: true }).click()
      assert.equal(await page.locator('#case-study').count(), 0)
      await page.keyboard.press('Enter')
      await assertCaseStudy(titles[0])
    }
    await page.getByRole('button', { name: `View ${titles[1]} case study`, exact: true }).click()
    await assertCaseStudy(titles[1])
    await page.locator('.project-card.is-selected .project-view').click()
    assert.equal(await page.locator('#case-study').count(), 0)
    await page.keyboard.press('Enter')
    await assertCaseStudy(titles[1])
    await page.getByRole('button', { name: 'Personal projects, 2 projects', exact: true }).click()
    assert.equal(await page.locator('#case-study').count(), 0, 'Changing filters must close the open case study')
    await page.getByRole('button', { name: 'All, 10 projects', exact: true }).click()
  }
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  console.log('Repeated case-study opening, closing, switching, and wraparound passed on mobile and desktop.')
  const slider = page.getByRole('slider')
  await slider.focus()
  assert((await slider.getAttribute('aria-valuetext')).includes('OCT 2022'))
  await page.keyboard.press('ArrowLeft')
  assert((await slider.getAttribute('aria-valuetext')).includes('SEP 2022'))
  await page.keyboard.press('Shift+ArrowLeft')
  assert((await slider.getAttribute('aria-valuetext')).includes('SEP 2021'))
  await page.keyboard.press('Home')
  assert((await slider.getAttribute('aria-valuetext')).includes('JAN 2014'))
  await page.keyboard.press('ArrowLeft')
  assert((await slider.getAttribute('aria-valuetext')).includes('JAN 2014'), 'Cursor must clamp at its first month')
  await page.keyboard.press('End')
  assert((await slider.getAttribute('aria-valuetext')).includes('NOW'))
  const trackBounds = await slider.boundingBox()
  await page.mouse.move(trackBounds.x + trackBounds.width * .3, trackBounds.y + 110)
  await page.mouse.down()
  await page.mouse.move(trackBounds.x + trackBounds.width * .55, trackBounds.y + 110)
  await page.mouse.up()
  assert(Number(await slider.getAttribute('aria-valuenow')) > Number(await slider.getAttribute('aria-valuemin')))
  await page.getByRole('button', { name: 'Play career', exact: false }).click()
  await page.getByRole('button', { name: 'Pause', exact: false }).waitFor()
  await page.waitForTimeout(250)
  await page.getByRole('button', { name: 'Pause', exact: false }).click()
  const pausedMonth = await slider.getAttribute('aria-valuenow')
  await page.waitForTimeout(200)
  assert.equal(await slider.getAttribute('aria-valuenow'), pausedMonth, 'Pause must stop playback')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  assert.equal(await page.evaluate(() => getComputedStyle(document.documentElement).scrollBehavior), 'auto', 'Reduced motion must disable animated scrolling')
  assert.equal(await page.locator('.project-card').first().evaluate(card => getComputedStyle(card).animationName), 'none', 'Reduced motion must disable card animations')
  await page.getByRole('button', { name: 'Play career', exact: false }).click()
  await page.waitForFunction(() => document.querySelector('[role="slider"]')?.getAttribute('aria-valuetext')?.includes('NOW'))
  assert((await slider.getAttribute('aria-valuetext')).includes('NOW'))
  console.log('Timeline drag, keyboard controls, playback, and reduced motion passed.')
  await page.getByRole('button', { name: 'Copy email', exact: false }).click()
  await page.getByText('Copied ✓', { exact: true }).waitFor()
  assert.equal(await page.evaluate(() => navigator.clipboard.readText()), 'bolanteoc@gmail.com')
  await page.waitForTimeout(1700)
  await page.getByRole('button', { name: 'Copy email', exact: false }).waitFor()

  // Missing replacement artwork must leave an informative, stable placeholder.
  await page.route('**/work/viewfinder.jpg', route => route.abort())
  await page.reload()
  await page.locator('.project-image--viewfinder').scrollIntoViewIfNeeded()
  await page.locator('.project-image--viewfinder.is-placeholder').waitFor()
  const endAccessibility = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
  assert.equal(endAccessibility.violations.length, 0)
  assert.deepEqual(errors, [], 'Browser should have no unhandled JavaScript errors')
  const summary = { responsiveWidths: [360, 768, 1024, 1440], accessibilityViolations: 0, interactionChecks: 'passed', unhandledErrors: errors }
  await writeFile('.artifacts/test-results.json', JSON.stringify(summary, null, 2))
  console.log(JSON.stringify(summary, null, 2))
} finally {
  await browser.close()
}
